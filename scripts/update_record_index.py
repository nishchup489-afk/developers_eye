"""Regenerate the tables in 0_tech_docs/record-index.md from the records on disk.

Usage, from the repository root:

    python scripts/update_record_index.py          # rewrite the tables
    python scripts/update_record_index.py --check  # exit 1 if the index is stale or a record is broken
    python scripts/update_record_index.py --diff   # print what would change, write nothing

A record is any file named ``ADR-NNNN-*.md``, ``INC-NNNN-*.md`` or
``EXP-NNNN-*.md`` under ``0_tech_docs/<area>/<feature>/`` (``_templates`` is
skipped). Each row comes from the record itself:

    ID       front matter ``id`` (falls back to the file name)
    Feature  the folder the file sits in, ``<area>/<feature>``
    Record   front matter ``title`` (falls back to the first heading), linked
    Status   front matter ``status``

The tables live between the two marker comments below. Everything above them
(the intro text) is kept as written. On the first run, the old hand-written
tables from ``## Decisions`` down are replaced by the generated block.

Problems that make --check fail: two records with the same ID, a front matter
``id`` that does not match the file name, or a record with no title or status.
"""

from __future__ import annotations

import argparse
import difflib
import re
import subprocess
import sys
from pathlib import Path, PurePosixPath

DOCS = "0_tech_docs"
INDEX = f"{DOCS}/record-index.md"
START = "<!-- record-index:start -->"
END = "<!-- record-index:end -->"
SKIP_DIRS = {"_templates"}

KINDS = [  # (prefix, section heading)
    ("ADR", "Decisions"),
    ("INC", "Incidents"),
    ("EXP", "Experiments"),
]
NAME = re.compile(r"^(ADR|INC|EXP)-(\d{4})-.+\.md$")


def front_matter(text: str) -> dict[str, str]:
    """Flat ``key: value`` pairs from a leading YAML block (lists are ignored)."""
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end < 0:
        return {}
    meta: dict[str, str] = {}
    for line in text[3:end].splitlines():
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*?)\s*$", line)
        if m and m.group(2):
            meta[m.group(1)] = m.group(2).strip().strip("'\"")
    return meta


def first_heading(text: str, record_id: str) -> str:
    for line in text.splitlines():
        m = re.match(r"^#\s+(.+?)\s*$", line)
        if m:
            # "# ADR-0001: Title" -> "Title"
            return re.sub(rf"^{re.escape(record_id)}\s*[:\-–]\s*", "", m.group(1))
    return ""


def cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ").strip()


def collect(root: Path) -> tuple[dict[str, list[tuple[int, str]]], list[str]]:
    rows: dict[str, list[tuple[int, str]]] = {prefix: [] for prefix, _ in KINDS}
    problems: list[str] = []
    seen: dict[str, str] = {}
    docs = root / DOCS
    for path in sorted(docs.rglob("*.md")):
        rel = path.relative_to(docs)
        m = NAME.match(path.name)
        if not m or rel.parts[0] in SKIP_DIRS or len(rel.parts) < 2:
            continue
        prefix, number = m.group(1), m.group(2)
        file_id = f"{prefix}-{number}"
        text = path.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n")
        meta = front_matter(text)
        record_id = meta.get("id", file_id)
        link = PurePosixPath(*rel.parts).as_posix()

        if record_id != file_id:
            problems.append(f"{link}: front matter id {record_id} does not match file name {file_id}")
        if file_id in seen:
            problems.append(f"{file_id} is used twice: {seen[file_id]} and {link}")
        seen[file_id] = link

        title = meta.get("title") or first_heading(text, file_id)
        status = meta.get("status", "")
        if not title:
            problems.append(f"{link}: no title in front matter or heading")
        if not status:
            problems.append(f"{link}: no status in front matter")

        feature = PurePosixPath(*rel.parts[:-1]).as_posix()
        href = link.replace(" ", "%20")
        rows[prefix].append((
            int(number),
            f"| {file_id} | {cell(feature)} | [{cell(title) or path.name}]({href}) | {cell(status)} |",
        ))
    return rows, problems


def render(rows: dict[str, list[tuple[int, str]]]) -> str:
    out = ["<!-- Generated by scripts/update_record_index.py from each record's front matter. Do not edit below by hand. -->", ""]
    for prefix, heading in KINDS:
        out += [f"## {heading}", "", "| ID | Feature | Record | Status |", "| --- | --- | --- | --- |"]
        out += [line for _, line in sorted(rows[prefix])] or ["| | | _none yet_ | |"]
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def splice(existing: str, body: str) -> str:
    if START in existing and END in existing:
        before, rest = existing.split(START, 1)
        _, after = rest.split(END, 1)
        return f"{before}{START}\n{body}{END}{after}"
    # First run: keep the intro, replace the hand-written tables.
    cut = existing.find("\n## Decisions")
    intro = existing if cut < 0 else existing[: cut + 1]
    return f"{intro.rstrip()}\n\n{START}\n{body}{END}\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if stale or a record is broken")
    parser.add_argument("--diff", action="store_true", help="print the change and write nothing")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()

    root = Path(subprocess.run(["git", "rev-parse", "--show-toplevel"], check=True,
                               capture_output=True, text=True).stdout.strip())
    index = root / INDEX
    raw = index.read_bytes().decode("utf-8") if index.exists() else "# Decision, incident and experiment index\n"
    crlf = "\r\n" in raw
    existing = raw.replace("\r\n", "\n")

    rows, problems = collect(root)
    new = splice(existing, render(rows))
    for problem in problems:
        print(f"record-index: {problem}", file=sys.stderr)

    stale = new != existing
    if args.diff:
        sys.stdout.writelines(difflib.unified_diff(
            existing.splitlines(True), new.splitlines(True), INDEX, INDEX + " (generated)"))
        return 0
    if args.check:
        if stale:
            print(f"stale: {INDEX} (run python scripts/update_record_index.py)")
        return 1 if stale or problems else 0
    if stale:
        index.write_bytes((new.replace("\n", "\r\n") if crlf else new).encode("utf-8"))
    if not args.quiet:
        total = sum(len(r) for r in rows.values())
        print(f"{'updated' if stale else 'up to date'}: {INDEX} ({total} records)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
