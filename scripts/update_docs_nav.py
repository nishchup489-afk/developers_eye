"""Regenerate the documentation map at the end of every README.md.

Usage, from the repository root:

    python scripts/update_docs_nav.py          # rewrite the maps
    python scripts/update_docs_nav.py --check  # exit 1 if any map is stale

Only files tracked by git are listed, so ignored folders (.venv, node_modules,
.vscode, .pytest_cache) never appear. The map lives between the two marker
comments below; everything outside the markers is left untouched.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path, PurePosixPath

START = "<!-- docs-nav:start -->"
END = "<!-- docs-nav:end -->"

# Agent instruction files are not project documentation.
EXCLUDED = {"frontend/AGENTS.md", "frontend/CLAUDE.md"}

# Labels for files whose first heading is missing or not a useful title.
LABELS = {
    "README.md": "Project overview",
    "technical_handoff.md": "Technical handoff",
    "crawler/src/crawler/README.md": "Crawler package",
    "crawler/src/crawler/policy_and_politeness/README.md": "Policy components overview",
    "crawler/src/crawler/policy_and_politeness/docs/README.md": "Policy docs introduction",
    "crawler/src/crawler/schedular/DOCS/REPOSITORY_README.md": "Scheduler repository and target states",
    "crawler/src/crawler/schedular/DOCS/new_concept_to_note.md": "Scheduler concepts to note",
    "crawler/src/crawler/seed/guide.md": "Seed guide",
    "crawler/src/crawler/seed/seed_list.md": "Seed list",
    "crawler/src/crawler/test/order.md": "Test run order",
    "crawler/src/indexer/docs/config.md": "Indexer configuration",
    "crawler/src/indexer/docs/file_task.md": "Indexer file responsibilities",
}

# (title, path prefix) in display order. The first matching prefix wins.
SECTIONS = [
    ("Start here", ("README.md", "technical_handoff.md", "crawler/DEVELOPERS_EYE_CHECKLIST.md")),
    ("Backend (FastAPI, database)", ("backend/",)),
    ("Crawler: seeds and frontier", ("crawler/src/crawler/README.md", "crawler/src/crawler/seed/", "crawler/src/crawler/frontier/", "crawler/src/crawler/schedular/")),
    ("Crawler: fetch and policy", ("crawler/src/crawler/fetcher/", "crawler/src/crawler/policy_and_politeness/")),
    ("Crawler: parse, process, write", ("crawler/src/crawler/parser/", "crawler/src/crawler/processing/", "crawler/src/crawler/writer/")),
    ("Crawler: worker and ingestion", ("crawler/src/crawler/worker/", "crawler/tests/")),
    ("Crawler: fix log", ("crawler/src/crawler/test/",)),
    ("Indexer", ("crawler/src/indexer/",)),
    ("Frontend (Next.js, admin)", ("frontend/",)),
]


def tracked_docs(root: Path) -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "-z", "--", "*.md"],
        cwd=root, check=True, capture_output=True,
    ).stdout.decode("utf-8")
    return sorted(p for p in out.split("\0") if p and p not in EXCLUDED)


def first_heading(path: Path) -> str | None:
    in_code = False
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if line.lstrip().startswith("```"):
            in_code = not in_code
            continue
        if not in_code and line.startswith("# "):
            return line[2:].strip() or None
    return None


def label_for(root: Path, doc: str) -> str:
    if doc in LABELS:
        return LABELS[doc]
    name = PurePosixPath(doc)
    if doc.startswith("backend/docs/db/"):
        return f"Table notes: {name.stem}"
    if name.name == "test_case.md":
        return f"{name.parent.parent.name.replace('_', ' ').capitalize()} test cases"
    heading = first_heading(root / doc)
    if heading:
        return re.sub(r"\s+", " ", heading.replace("`", "")).rstrip(".")
    return name.stem.replace("_", " ").capitalize()


def section_of(doc: str) -> tuple[str, int]:
    """Return the section title and the matching prefix's position in it."""
    for title, prefixes in SECTIONS:
        for index, p in enumerate(prefixes):
            if doc == p or (p.endswith("/") and doc.startswith(p)):
                return title, index
    return "Other", 0


def render(root: Path, docs: list[str], readme: str) -> str:
    here = PurePosixPath(readme).parent
    groups: dict[str, list[str]] = {}
    for doc in sorted(docs, key=lambda d: (section_of(d)[1], d)):
        groups.setdefault(section_of(doc)[0], []).append(doc)

    lines = [
        START,
        "## Documentation map",
        "",
        "Every project doc, grouped by area. Generated by `scripts/update_docs_nav.py`; "
        "edit that script, not this list.",
    ]
    for title in [t for t, _ in SECTIONS] + ["Other"]:
        if title not in groups:
            continue
        lines += ["", f"**{title}**", ""]
        for doc in groups[title]:
            rel = os.path.relpath(doc, here.as_posix() or ".").replace(os.sep, "/")
            link = f"[{label_for(root, doc)}]({rel.replace(' ', '%20')})"
            marker = " (you are here)" if doc == readme else ""
            lines.append(f"- {link} `{doc}`{marker}")
    lines.append(END)
    return "\n".join(lines)


def updated_text(text: str, block: str) -> str:
    newline = "\r\n" if "\r\n" in text else "\n"
    body = text.replace("\r\n", "\n")
    if START in body and END in body:
        head, rest = body.split(START, 1)
        tail = rest.split(END, 1)[1]
        body = head + block + tail
    else:
        body = body.rstrip("\n")
        body = (body + "\n\n" if body else "") + block + "\n"
    return body.replace("\n", newline)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[1]
    docs = tracked_docs(root)
    readmes = [d for d in docs if PurePosixPath(d).name.endswith("README.md")]

    stale = []
    for readme in readmes:
        path = root / readme
        with path.open("r", encoding="utf-8", newline="") as fh:
            text = fh.read()
        new = updated_text(text, render(root, docs, readme))
        if new != text:
            stale.append(readme)
            if not args.check:
                with path.open("w", encoding="utf-8", newline="") as fh:
                    fh.write(new)

    verb = "stale" if args.check else "updated"
    print(f"{len(stale)} of {len(readmes)} README files {verb}")
    for readme in stale:
        print(f"  {readme}")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
