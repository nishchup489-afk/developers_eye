"""Full selector -> service -> writer -> repository -> PostgreSQL smoke test.

This test is opt-in via TEST_DATABASE_URL and uses ONLY temporary tables on
its own PostgreSQL connection. It never writes to your real document/search
index tables, and those temporary tables disappear when the connection closes.

Run from crawler/:
    poetry run pytest src/indexer/tests/test_final_indexer.py -v -rs
"""

from __future__ import annotations

import hashlib
import json
import os

import pytest
from sqlalchemy import text
from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine
from sqlalchemy.pool import NullPool

from indexer.analyzer import analyze_index_document
from indexer.builder import build_index_document, calculate_index_hash, prepare_index_document
from indexer.config import IndexerConfig
from backend.models.documents import Document
from datetime import datetime, timezone
from sqlalchemy.dialects import postgresql
from indexer.schemas import IndexStatus
from indexer.selector import select_index_candidates, select_removal_candidates
from indexer.service import index_candidate, remove_candidate
from indexer.vector import build_search_vectors
from indexer.writer import persist_search_vectors


# The ORM queries are intentionally executed against TEMP tables with these
# names; pg_temp takes precedence over persistent tables for relation lookup.
_TEMP_DOCUMENT = """
CREATE TEMP TABLE document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL,
    last_crawl_target_id BIGINT,
    canonical_url TEXT NOT NULL UNIQUE,
    document_type TEXT NOT NULL,
    title TEXT NOT NULL,
    description TEXT,
    body TEXT,
    author TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    content_hash TEXT NOT NULL,
    published_at TIMESTAMPTZ,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_available BOOLEAN NOT NULL DEFAULT true,
    unavailable_at TIMESTAMPTZ,
    unavailable_http_status INTEGER
) ON COMMIT PRESERVE ROWS
"""

_TEMP_SEARCH_INDEX = """
CREATE TEMP TABLE search_index (
    document_id BIGINT PRIMARY KEY REFERENCES document(id) ON DELETE CASCADE,
    search_vector TSVECTOR NOT NULL,
    code_vector TSVECTOR NOT NULL,
    indexed_hash TEXT NOT NULL,
    indexed_at TIMESTAMPTZ NOT NULL DEFAULT now()
) ON COMMIT PRESERVE ROWS
"""


async def _candidates(factory, config: IndexerConfig):
    async with factory() as session:
        return await select_index_candidates(session, config=config)


async def _removals(factory, config: IndexerConfig):
    async with factory() as session:
        return await select_removal_candidates(session, config=config)


async def _stored(factory, document_id: int):
    async with factory() as session:
        result = await session.execute(
            text("""
            SELECT indexed_hash,
                   search_vector @@ plainto_tsquery('english', 'python') AS matches_python,
                   code_vector @@ plainto_tsquery('simple', 'async') AS matches_async,
                   search_vector @@ plainto_tsquery('english', 'quasarwhim') AS matches_new_term
            FROM search_index WHERE document_id = :document_id
            """),
            {"document_id": document_id},
        )
        return result.mappings().one_or_none()


def test_final_local_document_to_sql_expression() -> None:
    """Exercise the real builder/analyzer/vector types without PostgreSQL."""
    config = IndexerConfig(index_version=2)
    row = Document(
        id=1,
        source_id=7,
        canonical_url="https://docs.example.test/python/asyncio",
        document_type="documentation",
        title="Python Async Tutorial",
        description="Introduction to asyncio",
        body="Python asyncio supports async programming",
        metadata_={
            "tags": ["Python", "python"],
            "headings": ["Async functions"],
            "code_blocks": ["async def example():\n    return 42"],
        },
        content_hash=hashlib.sha256(b"fixture content").hexdigest(),
        updated_at=datetime(2026, 10, 27, tzinfo=timezone.utc),
        is_available=True,
    )
    prepared = prepare_index_document(row, config=config)
    assert prepared.tags == ("Python",)
    assert prepared.source_id == 7
    fingerprint = calculate_index_hash(prepared, config=config)
    assert fingerprint.startswith("v2:")
    analyzed = analyze_index_document(prepared, config=config)
    assert any(f.name == "title" and f.weight == "A" for f in analyzed.text_fields)
    assert any(f.name == "code_blocks" for f in analyzed.code_fields)
    vectors = build_search_vectors(analyzed, config=config)
    assert vectors.document_id == 1

    sql = str(vectors.text_vector.compile(dialect=postgresql.dialect()))
    code_sql = str(vectors.code_vector.compile(dialect=postgresql.dialect()))
    assert "to_tsvector" in sql
    assert "setweight" in sql
    assert "to_tsvector" in code_sql
    # The document text is bound data; it is not interpolated into SQL.
    assert "Python Async Tutorial" not in sql
    assert "async def example" not in code_sql


@pytest.mark.asyncio
async def test_final_indexer_lifecycle_against_postgresql() -> None:
    """Verify build, search, skip, stale, reindex, version, removal, revival.

    A real PostgreSQL server is required for actual TSVECTOR execution, but
    persistent application tables are never modified by this test.
    """
    url = os.getenv("TEST_DATABASE_URL")
    if not url:
        pytest.skip("Set TEST_DATABASE_URL to enable the PostgreSQL integration test")
    if not url.startswith("postgresql+asyncpg://"):
        pytest.fail("TEST_DATABASE_URL must use postgresql+asyncpg://")
    pytest.importorskip("asyncpg")

    engine = create_async_engine(url, poolclass=NullPool, pool_pre_ping=True)
    try:
        async with engine.connect() as connection:
            # One connection keeps the TEMP tables visible to every session.
            await connection.execute(text(_TEMP_DOCUMENT))
            await connection.execute(text(_TEMP_SEARCH_INDEX))
            await connection.commit()

            factory = async_sessionmaker(
                bind=connection, expire_on_commit=False, autoflush=False
            )
            cfg = IndexerConfig(index_version=2)
            body = "Python asynchronous programming with await and asyncio."
            content_hash = hashlib.sha256(body.encode("utf-8")).hexdigest()
            metadata = json.dumps({
                "headings": ["Async functions"],
                "tags": ["python", "asyncio"],
                "code_blocks": ["async def run():\n    return 42"],
            })

            # 1. Insert one real source row into the TEMP document table.
            inserted = await connection.execute(
                text("""
                    INSERT INTO document (
                        source_id, canonical_url, document_type, title,
                        description, body, metadata, content_hash, updated_at
                    ) VALUES (
                        :source_id, :url, 'documentation', :title,
                        :description, :body, CAST(:metadata AS jsonb),
                        :content_hash, now() - interval '1 day'
                    ) RETURNING id
                """),
                {
                    "source_id": 7,
                    "url": "https://docs.example.test/python/asyncio",
                    "title": "Python Async Tutorial",
                    "description": "Introduction to asyncio",
                    "body": body,
                    "metadata": metadata,
                    "content_hash": content_hash,
                },
            )
            document_id = inserted.scalar_one()
            await connection.commit()

            # 2. Selector sees the unindexed available source.
            candidates = await _candidates(factory, cfg)
            assert [c.document_id for c in candidates] == [document_id]
            candidate = candidates[0]

            # 3. Full service pipeline actually executes PostgreSQL FTS.
            first = await index_candidate(factory, candidate, config=cfg)
            assert first.status is IndexStatus.INDEXED
            assert first.indexed_hash is not None
            assert first.indexed_hash.startswith("v2:")
            stored = await _stored(factory, document_id)
            assert stored is not None
            assert stored["indexed_hash"] == first.indexed_hash
            assert stored["matches_python"] is True
            assert stored["matches_async"] is True
            assert stored["matches_new_term"] is False
            assert await _candidates(factory, cfg) == []

            # 4. Same revision and version must not reindex.
            unchanged = await index_candidate(factory, candidate, config=cfg)
            assert unchanged.status is IndexStatus.UNCHANGED
            assert (await _stored(factory, document_id))["indexed_hash"] == first.indexed_hash

            # 5. A prepared vector must never overwrite a changed source.
            async with factory() as session:
                prepared = await build_index_document(session, candidate, config=cfg)
            old_hash = calculate_index_hash(prepared, config=cfg)
            old_vectors = build_search_vectors(
                analyze_index_document(prepared, config=cfg), config=cfg
            )
            await connection.execute(
                text("""
                    UPDATE document
                    SET title = :title, body = :body,
                        content_hash = :content_hash,
                        updated_at = clock_timestamp()
                    WHERE id = :document_id
                """),
                {
                    "title": "Python Concurrency and quasarwhim",
                    "body": "Concurrent tasks use async and await. quasarwhim",
                    "content_hash": hashlib.sha256(b"updated source").hexdigest(),
                    "document_id": document_id,
                },
            )
            await connection.commit()
            stale_write = await persist_search_vectors(
                factory, old_vectors, indexed_hash=old_hash
            )
            assert stale_write is IndexStatus.STALE
            assert (await _stored(factory, document_id))["indexed_hash"] == first.indexed_hash

            # 6. Old selector candidate is stale; a fresh one reindexes.
            stale_read = await index_candidate(factory, candidate, config=cfg)
            assert stale_read.status is IndexStatus.STALE
            fresh_candidates = await _candidates(factory, cfg)
            assert [c.document_id for c in fresh_candidates] == [document_id]
            updated = await index_candidate(factory, fresh_candidates[0], config=cfg)
            assert updated.status is IndexStatus.INDEXED
            assert updated.indexed_hash != first.indexed_hash
            assert (await _stored(factory, document_id))["matches_new_term"] is True

            # 7. Index format changes trigger a rebuild even if text is unchanged.
            cfg3 = IndexerConfig(index_version=3)
            version_candidates = await _candidates(factory, cfg3)
            assert [c.document_id for c in version_candidates] == [document_id]
            versioned = await index_candidate(factory, version_candidates[0], config=cfg3)
            assert versioned.status is IndexStatus.INDEXED
            assert versioned.indexed_hash.startswith("v3:")

            # 8. Soft-unavailable source is removed and removal is idempotent.
            await connection.execute(
                text("""
                    UPDATE document SET is_available = false, updated_at = clock_timestamp()
                    WHERE id = :id
                """),
                {"id": document_id},
            )
            await connection.commit()
            assert await _candidates(factory, cfg3) == []
            assert document_id in await _removals(factory, cfg3)
            removal = await remove_candidate(factory, document_id)
            assert removal.status is IndexStatus.REMOVED
            assert await _stored(factory, document_id) is None
            again = await remove_candidate(factory, document_id)
            assert again.status is IndexStatus.SKIPPED

            # 9. Revived document can be indexed; old removal must not delete it.
            await connection.execute(
                text("""
                    UPDATE document SET is_available = true, updated_at = clock_timestamp()
                    WHERE id = :id
                """),
                {"id": document_id},
            )
            await connection.commit()
            reselected = await _candidates(factory, cfg3)
            assert len(reselected) == 1
            revived = await index_candidate(factory, reselected[0], config=cfg3)
            assert revived.status is IndexStatus.INDEXED
            assert (await remove_candidate(factory, document_id)).status is IndexStatus.STALE
            assert await _stored(factory, document_id) is not None

            # 10. Hard deletion cascades to the index through the FK.
            await connection.execute(
                text("DELETE FROM document WHERE id = :id"), {"id": document_id}
            )
            await connection.commit()
            assert await _stored(factory, document_id) is None
    finally:
        await engine.dispose()
